//! Interface strings, Italian and English, in one table checked by the
//! compiler: a missing translation does not build.

use serde::{Deserialize, Serialize};

#[derive(Debug, Clone, Copy, Default, PartialEq, Eq, Serialize, Deserialize)]
pub enum Lang {
    #[default]
    It,
    En,
}

impl Lang {
    /// The language of the computer, when it is one of ours.
    pub fn detect() -> Lang {
        let env = ["LC_ALL", "LC_MESSAGES", "LANG"].iter().find_map(|k| std::env::var(k).ok()).unwrap_or_default();
        if env.is_empty() || env.starts_with("it") { Lang::It } else { Lang::En }
    }

    pub fn strings(self) -> &'static Strings {
        match self {
            Lang::It => &IT,
            Lang::En => &EN,
        }
    }
}

